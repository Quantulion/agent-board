export const CATALOGS = { ru: RU, en: EN };

// Текущие строки интерфейса; содержимое меняет setLanguage, сам объект остаётся тем же.
export const T = {};

export const STATUSES = [
  { id: 'not_started', color: '--s-todo' },
  { id: 'blocked', color: '--s-blocked' },
  { id: 'in_progress', color: '--s-progress' },
  { id: 'waiting_answer', color: '--s-answer' },
  { id: 'queued', color: '--s-queue' },
  { id: 'in_review', color: '--s-review' },
  { id: 'approved', color: '--s-approved' },
  { id: 'sent', color: '--s-sent' },
  { id: 'done', color: '--s-done' },
  { id: 'cancelled', color: '--s-cancelled' },
];

const STATUS_BY_ID = new Map(STATUSES.map(st => [st.id, st]));

export function statusInfo(id) {
  return STATUS_BY_ID.get(id) || { id, label: id, color: '--s-todo' };
}

export const STAGES = [{ id: 'decomposition' }, { id: 'tracker' }, { id: 'work' }, { id: 'done' }];

let current = null;

// Язык интерфейса по языку проекта: русский только для русского, остальные языки — английский.
export function uiLanguage(language) {
  const text = String(language || '').trim().toLowerCase();
  if (!text) return 'ru';
  return /^(ru|рус|russian)/.test(text) ? 'ru' : 'en';
}

export function currentLanguage() {
  return current;
}

// Переключает строки интерфейса; возвращает true, если язык сменился.
export function setLanguage(language) {
  const next = uiLanguage(language);
  if (next === current) return false;
  current = next;
  const catalog = CATALOGS[next];
  for (const key of Object.keys(T)) delete T[key];
  Object.assign(T, catalog);
  for (const st of STATUSES) st.label = catalog.statusLabels[st.id];
  for (const st of STAGES) st.label = catalog.stageLabels[st.id];
  if (globalThis.document && globalThis.document.documentElement) globalThis.document.documentElement.lang = next;
  return true;
}

setLanguage('ru');

export function tasksCount(n) {
  return T.tasksCount(n);
}
